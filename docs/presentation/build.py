def write(shape, *lines, color: str | None = None) -> None:
    """Заменить текст, сохранив оформление заготовки.

    Формат живёт в первом run'е и в свойствах абзаца, поэтому текст кладётся
    в существующий run, а лишние абзацы клонируются с него же.

    `color` нужен там, где заполнитель в шаблоне пустой: такие блоки
    наследуют из макета белый текст, который на светлой карточке не виден.
    Строка может быть кортежем `(текст, {"color": …, "bold": True})`.
    """
    frame = shape.text_frame
    first = frame.paragraphs[0]

    def apply(para, item) -> None:
        text, opts = item if isinstance(item, tuple) else (item, {})
        run = para.runs[0] if para.runs else para.add_run()
        run.text = text
        for extra in para.runs[1:]:
            extra._r.getparent().remove(extra._r)
        tone = opts.get("color", color)
        if tone:
            run.font.color.rgb = RGBColor.from_string(tone)
        if opts.get("bold") is not None:
            run.font.bold = opts["bold"]

    apply(first, lines[0])
    for para in frame.paragraphs[1:]:
        para._p.getparent().remove(para._p)
    for line in lines[1:]:
        element = copy.deepcopy(first._p)
        first._p.getparent().append(element)
        apply(_Paragraph(element, frame), line)


def picture(slide, idx, name: str, box_in: tuple | None = None):
    """Скриншот в заполнитель.

    `box_in` — явная рамка (x, y, w, h) в дюймах: нужна там, где заполнитель
    заготовки не несёт своей геометрии и наследует её от макета, из-за чего
    картинка уезжает на чужое место. Кадрирование по центру считаем сами.
    """
    path = SHOTS / name
    if not path.exists():
        raise FileNotFoundError(f"нет снимка {path}")
    pic = ph(slide, idx).insert_picture(str(path))
    if box_in:
        left, top, width, height = (Inches(v) for v in box_in)
        pic.left, pic.top, pic.width, pic.height = left, top, width, height
        with Image.open(path) as img:
            img_ratio = img.width / img.height
        box_ratio = width / height
        pic.crop_left = pic.crop_right = pic.crop_top = pic.crop_bottom = 0
        if img_ratio > box_ratio:                 # шире рамки — режем бока
            cut = (1 - box_ratio / img_ratio) / 2
            pic.crop_left = pic.crop_right = cut
        else:                                     # выше рамки — режем верх и низ
            cut = (1 - img_ratio / box_ratio) / 2
            pic.crop_top = pic.crop_bottom = cut
    return pic


def place_picture(slide, name: str, box_in: tuple):
    """Свободная картинка: вписывается в рамку целиком, по центру.

    Нужна там, где в заготовке нет заполнителя под изображение.
    """
    path = SHOTS / name
    left, top, width, height = (Inches(v) for v in box_in)
    with Image.open(path) as img:
        ratio = img.width / img.height
    if width / height > ratio:            # рамка шире картинки — равняем по высоте
        size = (int(height * ratio), height)
    else:
        size = (width, int(width / ratio))
    pic = slide.shapes.add_picture(str(path), left, top, size[0], size[1])
    pic.left = left + int((width - pic.width) / 2)
    pic.top = top + int((height - pic.height) / 2)
    return pic


def drop(shape) -> None:
    shape._element.getparent().remove(shape._element)


def drop_empty(slide) -> None:
    """Убрать незаполненные заполнители, чтобы не светились подсказки."""
    for shape in list(slide.placeholders):
        if shape.placeholder_format.idx in (2, 3, 4):      # дата, колонтитул, номер
            continue
        if shape.has_text_frame and not shape.text_frame.text.strip():
            drop(shape)


def arrange(pres, order: list[int]) -> None:
    """Оставить слайды с указанными исходными номерами в заданном порядке."""
    id_list = pres.slides._sldIdLst
    ids = list(id_list)
    keep = [ids[i] for i in order]
    for element in ids:
        if element not in keep:
            pres.part.drop_rel(element.get(qn("r:id")))
        id_list.remove(element)
    for element in keep:
        id_list.append(element)


