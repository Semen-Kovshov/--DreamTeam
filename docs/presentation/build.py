# --- утилиты -------------------------------------------------------------


def ph(slide, idx):
    """Заполнитель по индексу."""
    for shape in slide.placeholders:
        if shape.placeholder_format.idx == idx:
            return shape
    raise KeyError(f"на слайде нет заполнителя {idx}")


def box(slide, needle: str):
    """Текстовый блок заготовки — по фрагменту его текста-подсказки."""
    for shape in slide.shapes:
        if shape.has_text_frame and needle.lower() in shape.text_frame.text.lower():
            return shape
    raise KeyError(f"на слайде нет блока с текстом «{needle}»")


